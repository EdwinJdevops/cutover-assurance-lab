CREATE TABLE ledger_entries (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 event_id UUID NOT NULL,
 account_id TEXT NOT NULL,
 amount BIGINT NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(event_id,account_id)
);
CREATE TABLE lab_control (
 singleton BOOLEAN PRIMARY KEY DEFAULT TRUE CHECK(singleton),
 writes_fenced BOOLEAN NOT NULL DEFAULT FALSE
);
INSERT INTO lab_control(singleton) VALUES(TRUE);
CREATE OR REPLACE FUNCTION block_fenced_writes() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF (SELECT writes_fenced FROM lab_control WHERE singleton) THEN
  RAISE EXCEPTION 'writes fenced';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER ledger_write_fence BEFORE INSERT OR UPDATE OR DELETE ON ledger_entries
 FOR EACH ROW EXECUTE FUNCTION block_fenced_writes();
